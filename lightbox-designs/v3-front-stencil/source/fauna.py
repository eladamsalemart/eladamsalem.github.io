def giraffe():
    body = shape([
        (-30, -82), (-10, -88), (8, -93), (16, -100), (28, -116), (38, -130), (43, -137), (44.5, -143, C),
        (46, -139), (48, -144, C), (49.5, -139), (54, -138), (63, -133, C), (61, -130), (53, -131),
        (47, -128), (40, -118), (30, -100), (22, -86), (12, -78), (-6, -72), (-22, -72), (-30, -74)], res=10)
    legs = _legs([([(-25, -76), (-28, -40), (-26, 0)], 5, 2.0), ([(-19, -74), (-18, -38), (-15, 0)], 4.4, 1.8),
                  ([(13, -80), (15, -40), (17, 0)], 4.6, 1.9), ([(7, -78), (6, -40), (9, 0)], 4.2, 1.8)])
    tail = U(stroke([(-30, -80), (-34, -66), (-35, -54)], 1.4, 1.3), ellipse(-35, -52, 1.4, 3))
    mane = stroke([(14, -98), (26, -116), (38, -132)], 1.6, 1.3)
    g = U(body, legs, tail, mane)
    # coat pattern: voronoi cells inside body
    rng = np.random.default_rng(7)
    pts = [(rng.uniform(-30, 50), rng.uniform(-140, -70)) for _ in range(38)]
    vor = voronoi_diagram(MultiPoint(pts))
    inner = body.buffer(-2.6)
    cells = []
    for c in vor.geoms:
        p = c.buffer(-1.3).intersection(inner)
        if p.area > 2.5:
            cells.append(p)
    g = g.difference(U(cells))
    return g.difference(circle(52, -136, 1.0))


