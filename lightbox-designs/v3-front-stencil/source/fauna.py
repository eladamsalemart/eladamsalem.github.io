def ibex():
    body = shape([
        (-30, -46), (-32.5, -49, C), (-33.5, -44, C), (-31.5, -38), (-28, -31), (-12, -27.5), (8, -27.5),
        (15, -30), (20, -37), (24, -46), (27, -52), (29.5, -51, C), (31, -55), (34, -60.5), (38.5, -61.5),
        (40.5, -64, C), (36, -69), (32, -72), (28, -71.5), (24, -73, C), (25.5, -69), (21, -62), (12, -50), (-8, -46.5)], res=10)
    legs = _legs([
        ([(-26, -34), (-29.5, -16), (-25.5, 0)], 5.4, 1.8), ([(-19, -30), (-21, -15), (-17, 0)], 4.6, 1.7),
        ([(12, -30), (13, -15), (14, 0)], 4.2, 1.7), ([(6, -29), (5, -15), (7.5, 0)], 4.0, 1.6)])
    horn_pts = [(31, -70), (28, -82), (20, -91), (9, -92), (1, -86), (-1, -80)]
    horn = stroke(horn_pts, 4.4, 1.6)
    # ridges on the horn
    from lib import curve
    c = curve(horn_pts, res=8)
    cuts = []
    for i in range(3, len(c) - 8, 3):
        x, y = c[i]
        dx, dy = c[i + 1] - c[i - 1]
        nx, ny = -dy, dx
        n = math.hypot(nx, ny)
        nx, ny = nx / n, ny / n
        cuts.append(line((x + nx * 0.4, y + ny * 0.4), (x + nx * 3.0, y + ny * 3.0), 0.9))
    horn = horn.difference(U(cuts))
    horn2 = stroke([(29, -70), (24, -83), (15, -89), (6, -88)], 2.6, 1.4)
    g = U(body, legs, horn, horn2)
    return g.difference(ellipse(33, -65.5, 1.1, 0.7))


